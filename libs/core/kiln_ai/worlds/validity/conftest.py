# ---- metric inputs ----


def cell(
    configuration: str = "A",
    input_no: int = 1,
    repeat: int = 1,
    system: str = "real",
    *,
    passed: bool | None = True,
    invalid: Any = None,
    half: str = "tuning",
    steps: int | None = 3,
    scores: dict[str, float] | None = None,
) -> Cell:
    return Cell(
        configuration=configuration,
        input_no=input_no,
        repeat=repeat,
        system=system,  # type: ignore[arg-type]
        half=half,  # type: ignore[arg-type]
        run_id=None if invalid == "reset_anomaly" and passed is None else "run",
        passed=passed,
        invalid=invalid,
        steps=steps,
        scores=scores,
    )


def paired_cell(
    configuration: str = "A",
    input_no: int = 1,
    repeat: int = 1,
    *,
    real: bool = True,
    world: bool = True,
    half: str = "tuning",
) -> PairedCell:
    return PairedCell(
        configuration=configuration,
        input_no=input_no,
        repeat=repeat,
        half=half,  # type: ignore[arg-type]
        real=real,
        world=world,
    )


def decision_record(
    run_id: str = "run-1",
    decision_index: int = 0,
    arm: str = "world",
    *,
    prefix: str = "divergent",
    agree: bool = True,
    configuration: str = "A",
    error: str | None = None,
) -> DecisionRecord:
    return DecisionRecord(
        run_id=run_id,
        configuration=configuration,
        decision_index=decision_index,
        arm=arm,  # type: ignore[arg-type]
        prefix=prefix,  # type: ignore[arg-type]
        recorded=[Call("create_note", {"text": "string"})],
        replayed=[Call("create_note", {"text": "string"})],
        name_match=agree,
        args_match=agree,
        agree=agree,
        usage=None,
        error=error,
    )

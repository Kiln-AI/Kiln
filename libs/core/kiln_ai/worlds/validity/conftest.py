"""Shared builders for the harness tests: synthetic traces, a toy world to replay against,
and small constructors for the dataclasses the statistics consume.

The traces are built by hand rather than generated by an adapter, so a test can put a
trace in exactly the shape it wants to measure — a dangling tool call, a parallel batch,
an error envelope — without a model in the loop.
"""

from __future__ import annotations

import json
